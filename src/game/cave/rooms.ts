export function mirror(rows: string[]): string[] {
  return rows.map((row) => [...row].reverse().join(""));
}

export function reachable(rows: string[], from: [number, number]): Set<string> {
  const seen = new Set<string>([`${from[0]},${from[1]}`]);
  const queue: [number, number][] = [from];
  while (queue.length) {
    const [x, y] = queue.shift()!;
    for (const [dx, dy] of [
      [1, 0],
      [-1, 0],
      [0, 1],
      [0, -1],
    ]) {
      const nx = x + dx;
      const ny = y + dy;
      const c = rows[ny]?.[nx];
      if (!c || c === "#" || c === "o" || seen.has(`${nx},${ny}`)) continue;
      seen.add(`${nx},${ny}`);
      queue.push([nx, ny]);
    }
  }
  return seen;
}
